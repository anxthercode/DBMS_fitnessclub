  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByRole('button', { name: 'Создать заказ и перейти к оплате' })).toBeDisabled()
  await page.getByRole('button', { name: 'Имитировать подтверждение email' }).click()
