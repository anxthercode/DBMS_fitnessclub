test('FAQ supports quick reversal, keyboard closing and reduced motion', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  const faq = page.locator('.fp-faqs details').first()
  const question = faq.locator('summary')
  await question.focus()
  await page.keyboard.press('Enter')
  await expect(question).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await expect.poll(() => faq.evaluate(element => element.getAnimations().length)).toBe(0)
  await expect(faq).toHaveAttribute('open', '')
  await page.setViewportSize({ width: 320, height: 850 })
  await expect(faq.locator('.fp-disclosure-content')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.locator('.fp-visiting').screenshot({ path: testInfo.outputPath('faq-open.png') })
  await question.press('Space')
  await expect(faq).not.toHaveAttribute('open', '')
  await expect(question).toBeFocused()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await question.press('Enter')
  await expect(faq).toHaveAttribute('open', '')
  expect(await faq.evaluate(element => element.getAnimations().length)).toBe(0)
  await question.press('Enter')
  await expect(faq).not.toHaveAttribute('open', '')
  await expect(page.locator('.trainer-demo-note')).toHaveCount(0)
})
