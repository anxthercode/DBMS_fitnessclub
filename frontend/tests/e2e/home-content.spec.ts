test('native touch swipe changes spaces without trapping vertical page scrolling', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile', 'Touch-specific browser interaction')
  await page.goto('/')
  const photo = page.locator('.space-photo')
  await photo.scrollIntoViewIfNeeded()
  const bounds = await photo.boundingBox()
  const session = await page.context().newCDPSession(page)
  const x = bounds!.x + bounds!.width * .85
  const y = bounds!.y + bounds!.height / 2
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  for (let step = 1; step <= 8; step++) {
    await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - bounds!.width * .7 * step / 8, y }] })
  }
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(page.locator('.space-current-title')).toHaveText('Кардиозона')
  const before = await page.evaluate(() => scrollY)
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: x - 100, y: y + 40 }] })
  for (let step = 1; step <= 8; step++) {
    await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - 100, y: y + 40 - step * 15 }] })
  }
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(before + 30)
  await expect(page.locator('.space-current-title')).toHaveText('Кардиозона')
  await session.detach()
})

