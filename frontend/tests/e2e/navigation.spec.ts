import { expect, test } from '@playwright/test'

test('home anchors work across routes, on reload and with keyboard focus', async ({ page }) => {
  await page.goto('/plans')
  async function follow(label: string) {
    const toggle = page.getByRole('button', { name: 'Открыть меню' })
    const mobile = await toggle.isVisible()
    if (mobile) await toggle.click()
    const navigation = page.getByRole('navigation', { name: mobile ? 'Мобильная навигация' : 'Основная навигация' })
    await navigation.getByRole('link', { name: label, exact: true }).focus()
    await page.keyboard.press('Enter')
  }
  await follow('О клубе')
  await expect(page).toHaveURL(/\/#club$/)
  await expect(page.locator('#club')).toBeFocused()
  await expect(page.locator('#club').getByRole('tab')).toHaveCount(4)
  const pool = page.locator('#club').getByRole('tab', { name: 'Бассейн', exact: true })
  await pool.focus()
  await page.keyboard.press('Enter')
  await expect(pool).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('#club').getByRole('tabpanel')).toContainText('Крытый бассейн и открытая часть — в одной водной зоне.')
  await follow('Контакты')
  await expect(page.locator('#contacts')).toBeFocused()
  const rect = await page.locator('#contacts').boundingBox()
  const header = await page.locator('header').boundingBox()
  expect(rect!.y).toBeGreaterThanOrEqual(header!.height)
  await page.goBack()
  await expect(page.locator('#club')).toBeFocused()
  await page.reload()
  await expect(page.locator('#club')).toBeFocused()
  await follow('О клубе')
  await expect(page.locator('#club')).toBeFocused()
  const question = page.locator('.fp-faqs summary').first()
  await question.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.fp-faqs details').first()).toHaveAttribute('open', '')
})

test('the former preview route shares navigation, typography and page content', async ({ page }) => {
  await page.goto('/design-preview#memberships')
  await expect(page.locator('h1')).toHaveText('NORTHSIDEFitness Club')
  await expect(page.locator('#memberships')).toBeFocused()
  await expect(page.getByRole('banner')).toHaveCount(1)
  await expect(page.getByRole('main')).toHaveCount(1)
  await expect(page.getByRole('contentinfo')).toHaveCount(1)
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await expect(page.locator('h1')).toHaveText('NORTHSIDEFitness Club')
  await page.locator('footer').getByRole('link', { name: 'Memberships', exact: true }).click()
  await expect(page).toHaveURL(/\/plans$/)
  await expect(page.locator('h1')).toHaveText('Memberships')
})
