import { expect, test } from '@playwright/test'

test('homepage price keeps its term and zones when continuing selection', async ({ page }) => {
  await page.goto('/#memberships')
  const picker = page.locator('.visit-picker')
  await expect(picker.locator('.picker-price')).toContainText('120,00')
  await expect(picker.locator('.picker-price')).toContainText('1 месяц')
  await picker.getByRole('radio', { name: 'Бассейн', exact: true }).check()
  await expect(picker.locator('.picker-price')).toContainText('90,00')
  await picker.getByRole('link', { name: /Продолжить выбор/ }).click()
  await expect(page.getByRole('radio', { name: '1 месяц', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: /Зал \+ кардио/ })).not.toBeChecked()
  await expect(page.locator('.offer-total')).toContainText('90,00')
})

test('mobile total follows selection and blocks invalid purchases', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/plans')
  const bar = page.getByTestId('mobile-purchase-bar')
  await expect(bar).toContainText('320,00')
  await page.getByRole('radio', { name: '1 месяц', exact: true }).check()
  await expect(bar).toContainText('120,00')
  await page.getByRole('checkbox', { name: /Зал \+ кардио/ }).uncheck()
  await page.getByRole('checkbox', { name: /Бассейн/ }).uncheck()
  await expect(bar.getByRole('button')).toBeDisabled()
  await page.getByRole('checkbox', { name: /Бассейн/ }).check()
  await expect(bar).toContainText('90,00')
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('mobile-selection.png') })
  await bar.getByRole('button').click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.locator('.commerce-items .commerce-card')).toHaveCount(1)
  await expect(bar).toContainText('90,00')
  await expect(page.locator('.promo-details')).not.toHaveAttribute('open', '')
  await expect(page.locator('.purchase-totals')).not.toContainText('Скидка')
  await expect(page.locator('.compact-footer')).toBeAttached()
  await expect(page.locator('.footer-visit')).toHaveCount(0)
  await expect(page.locator('main')).not.toContainText(/демо|учебн|имитац/i)
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await expect(bar.getByRole('link')).toHaveText('Sign in')
  await page.screenshot({ path: testInfo.outputPath('mobile-cart.png') })
})
