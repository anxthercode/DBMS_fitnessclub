import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { randomUUID } from 'node:crypto'

const api = 'http://127.0.0.1:8001/api/v1'
const password = 'Browser-test-2026!'
const headers = { 'X-Northside-Request': '1', 'Content-Type': 'application/json' }
async function register(page: Page, email: string, redirect = '/account') {
  await page.goto('/register?redirect=' + redirect)
  await page.getByLabel('Имя', { exact: true }).fill('Посетитель')
  await page.getByLabel('Фамилия', { exact: true }).fill('Проверка')
  await page.getByLabel('Электронная почта').fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByLabel('Повторите пароль').fill(password)
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click()
  await expect.poll(() => new URL(page.url()).pathname).toBe(redirect)
}
async function audit(page: Page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(result.violations.map(v => ({ rule: v.id, targets: v.nodes.map(n => n.target) }))).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}

test('training zone edits one cart line with price review and training-only payment', async ({ page }, testInfo) => {
  await page.goto('/training')
  await page.getByRole('button', { name: 'Добавить тренировку в корзину' }).first().click()
  await expect(page).toHaveURL(/\/cart$/)
  const before = await (await page.request.get(api + '/cart')).json()
  const edit = page.getByRole('button', { name: 'Изменить зону', exact: true })
  await edit.click()
  await page.getByRole('radio', { name: /Бассейн/ }).check()
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(edit).toBeFocused()
  expect(await (await page.request.get(api + '/cart')).json()).toEqual(before)
  await edit.click()
  await page.getByRole('radio', { name: /Бассейн/ }).check()
  await page.setViewportSize({ width: 320, height: 900 })
  await audit(page)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('training-zone-ru-320.png'), fullPage: true })
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await page.getByRole('button', { name: 'Orange theme', exact: true }).click()
  await audit(page)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('training-zone-en-orange-320.png'), fullPage: true })
  await page.getByRole('button', { name: 'RU', exact: true }).click()
  await page.route('**/api/v1/cart/items', route => route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ code: 'price_changed' }) }), { times: 1 })
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Цена или условия изменились')
  await page.getByRole('button', { name: 'Обновить цены занятий' }).click()
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Зона занятия сохранена')
  const after = await (await page.request.get(api + '/cart')).json()
  expect(after.items).toHaveLength(1)
  expect(after.items[0].id).toBe(before.items[0].id)
  expect(after.items[0].product.zones).toBe('pool')
  await page.setViewportSize({ width: 1280, height: 950 })
  await register(page, `training-edit-${randomUUID()}@example.com`, '/cart')
  await page.getByRole('button', { name: 'Создать заказ и перейти к оплате' }).click()
  await page.getByRole('button', { name: 'Оплатить в деморежиме' }).click()
  await expect(page.getByRole('status')).toContainText('Занятия доступны для записи')
  await expect(page.getByRole('link', { name: /Выбрать время/ })).toBeVisible()
  await expect(page.locator('.payment-success')).not.toContainText('Статус доступа')
  await expect(page.getByRole('link', { name: /Купленный доступ/ })).toHaveCount(0)
  await audit(page)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('training-paid-ru.png'), fullPage: true })
})

test('administrator reviews phone history and confirms a first visit without treating purchases as attendance', async ({ page }, testInfo) => {
  const suffix = randomUUID()
  const email = `visit-${suffix}@example.com`
  const phone = '+37529' + String(Math.floor(Math.random() * 10_000_000)).padStart(7, '0')
  await register(page, email)
  const profile = await page.request.patch(api + '/users/me', { headers, data: { first_name: 'Посетитель', last_name: 'Проверка', phone: '8 (0' + phone.slice(4, 6) + ') ' + phone.slice(6), locale: 'ru' } })
  expect(profile.ok(), await profile.text()).toBe(true)
  await page.goto('/plans?format=membership&zones=gym&months=1')
  await page.getByRole('button', { name: 'Добавить в корзину' }).click()
  await page.getByRole('button', { name: 'Создать заказ и перейти к оплате' }).click()
  await page.getByRole('button', { name: 'Оплатить в деморежиме' }).click()
  await expect(page.getByRole('link', { name: 'Купленный доступ 1' })).toBeVisible()
  const application = await page.request.post(api + '/first-visits', { headers, data: { name: 'Заявка ' + suffix, phone } })
  expect(application.status()).toBe(201)
  const id = (await application.json()).id
  expect((await page.request.get(api + '/admin/first-visits/' + id)).status()).toBe(403)
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Войти', exact: true })).toBeVisible()
  await page.goto('/login')
  await page.getByLabel('Электронная почта').fill('browser-admin@example.com')
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Войти в аккаунт' }).click()
  await expect(page).toHaveURL(/\/admin$/)
  await page.getByRole('button', { name: 'Первые визиты', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'Заявка ' + suffix }).getByRole('button', { name: 'Рассмотреть' }).click()
  await expect(page.getByRole('heading', { name: 'История по телефону' })).toBeVisible()
  await expect(page.locator('.visit-evidence')).toContainText('Посещения в системе не найдены')
  await page.locator('.visit-accounts summary').click()
  await expect(page.locator('.visit-accounts')).toContainText(email)
  await page.locator('.visit-history-entry summary').click()
  await expect(page.locator('.visit-history-body')).toContainText('Покупка абонемента не подтверждает посещение')
  await expect(page.getByRole('button', { name: 'Подтвердить визит', exact: true })).toBeDisabled()
  await audit(page)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('first-visit-ru-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 320, height: 900 })
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await page.getByRole('button', { name: 'Orange theme', exact: true }).click()
  await audit(page)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('first-visit-en-orange-320.png'), fullPage: true })
  await page.getByRole('button', { name: 'RU', exact: true }).click()
  const today = new Date().toLocaleDateString('en-CA', { timeZone: 'Europe/Minsk' })
  await page.getByLabel('Дата по Минску', { exact: true }).fill(today)
  await page.getByRole('combobox', { name: 'Зоны', exact: true }).selectOption('both')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Подтвердить визит', exact: true }).click()
  await expect(page.locator('.visit-person-heading')).toContainText('Подтверждён')
  await expect(page.getByRole('status')).toContainText('Решение сохранено')
  await page.getByRole('button', { name: 'Отметить вход', exact: true }).click()
  await expect(page.locator('.visit-person-heading')).toContainText('Использован')
  await expect(page.locator('.visit-evidence')).toContainText('Вход по этой заявке уже отмечен')
  await expect(page.getByRole('button', { name: 'Отметить вход', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Все заявки', exact: true }).click()
  await expect(page.locator('#visit-review-' + id)).toBeFocused()
})
