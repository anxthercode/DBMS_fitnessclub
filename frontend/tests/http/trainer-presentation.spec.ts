import { expect, test } from '@playwright/test'

test('persisted coursework coaches show portraits, filter by zone and link to their own schedule', async ({ page }, testInfo) => {
  await page.goto('/trainers')
  const profiles = page.locator('.trainer-profile')
  await expect(profiles.filter({ hasText: 'Даниэль Моро' }).locator('img')).toBeVisible()
  await expect(profiles.filter({ hasText: 'София Коваль' }).locator('img')).toBeVisible()
  await page.getByRole('button', { name: 'Бассейн', exact: true }).click()
  await expect(profiles.filter({ hasText: 'Даниэль Моро' })).toHaveCount(0)
  const swimmer = profiles.filter({ hasText: 'Максим Савицкий' })
  const portrait = swimmer.locator('img')
  await expect(portrait).toBeVisible()
  expect(await portrait.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true)
  const target = await swimmer.getByRole('link').getAttribute('href')
  await swimmer.getByRole('link').click()
  await expect(page).toHaveURL(new RegExp(target!.replace('?', '\\?') + '$'))
  await page.goto('/trainers')
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Training zone' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('trainers-mobile-en.png'), fullPage: true })
})

test('empty trainer list collapses the homepage section, while failures retain retry', async ({ page }) => {
  await page.route('**/api/v1/trainers', route => route.fulfill({ json: [] }))
  await page.goto('/')
  await expect(page.locator('.fp-coaches')).toBeHidden()
  await page.unroute('**/api/v1/trainers')
  await page.route('**/api/v1/trainers', route => route.fulfill({ status: 503, json: { code: 'database_unavailable' } }))
  await page.reload()
  await expect(page.locator('.fp-coaches').getByRole('button', { name: 'Повторить' })).toBeVisible({ timeout: 15000 })
  await page.unroute('**/api/v1/trainers')
  await page.locator('.fp-coaches').getByRole('button').click()
  await expect(page.locator('.fp-coaches .trainer-profile')).toHaveCount(3)
})
