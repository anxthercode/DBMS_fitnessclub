import { expect, test, type Page } from '@playwright/test'
import { randomUUID } from 'node:crypto'

const password = 'Browser-test-2026!'
async function login(page: Page, email: string) {
  await page.goto('/login')
  await page.getByLabel('Электронная почта').fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Войти в аккаунт' }).click()
  await expect(page).toHaveURL(/\/(admin|trainer|account)$/)
}
async function logout(page: Page) {
  await page.getByRole('button', { name: 'Выйти', exact: true }).filter({ visible: true }).first().click()
  await expect(page.getByRole('link', { name: 'Войти', exact: true }).filter({ visible: true }).first()).toBeVisible()
}

test('admin, trainer and client complete a paid training workflow and export reports', async ({ page }, testInfo) => {
  test.setTimeout(120_000)
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  const suffix = randomUUID()
  const coachEmail = `coach-${suffix}@example.com`
  const clientEmail = `client-${suffix}@example.com`
  await login(page, 'browser-admin@example.com')
  await expect(page).toHaveURL(/\/admin$/)
  await page.getByRole('button', { name: 'Тренеры', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить', exact: true }).click()
  const form = page.locator('.staff-form')
  await form.getByLabel('Email', { exact: true }).fill(coachEmail)
  await form.getByLabel('Начальный пароль').fill(password)
  await form.getByLabel('Имя', { exact: true }).fill('Новый')
  await form.getByLabel('Фамилия', { exact: true }).fill('Тренер')
  await form.getByRole('combobox', { name: 'Зоны', exact: true }).selectOption('gym')
  await form.getByLabel('Опыт, лет').fill('5')
  await form.getByLabel('Специализация (RU)').fill('Силовая подготовка')
  await form.getByLabel('Специализация (EN)').fill('Strength training')
  await form.getByLabel('Биография (RU)').fill('Персональные занятия в тренажёрном зале.')
  await form.getByLabel('Биография (EN)').fill('Personal sessions in the gym.')
  await form.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Изменения сохранены')
  await logout(page)
  await login(page, coachEmail)
  await expect(page).toHaveURL(/\/trainer$/)
  const day = new Date(Date.now() + 3 * 86_400_000).toISOString().slice(0, 10)
  await page.getByLabel('Начало по Минску', { exact: true }).fill(day + 'T12:00')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Расписание обновлено')
  await page.screenshot({ path: testInfo.outputPath('trainer-ru.png'), fullPage: true })
  const slotResponse = await page.request.get('http://127.0.0.1:8001/api/v1/staff/training-slots')
  const slots = await slotResponse.json() as { id: string }[]
  const slotId = slots.at(-1)!.id
  await logout(page)
  await page.goto('/register')
  await page.getByLabel('Имя', { exact: true }).fill('Новый')
  await page.getByLabel('Фамилия', { exact: true }).fill('Клиент')
  await page.getByLabel('Электронная почта').fill(clientEmail)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByLabel('Повторите пароль').fill(password)
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await page.goto('/plans?format=membership&zones=gym&months=1')
  await page.getByRole('button', { name: 'Добавить в корзину' }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await page.goto('/training')
  await page.getByRole('button', { name: 'Добавить тренировку в корзину' }).first().click()
  await expect(page.locator('.commerce-items .commerce-card')).toHaveCount(2)
  await page.getByRole('button', { name: 'Создать заказ и перейти к оплате' }).click()
  await page.getByRole('button', { name: 'Оплатить в деморежиме' }).click()
  await expect(page.getByRole('link', { name: /Оплаченные занятия и запись/ })).toBeVisible()
  await page.goto('/schedule/' + slotId)
  await page.getByRole('button', { name: 'Отправить заявку' }).click()
  await expect(page.locator('.booking-state')).toContainText('Ожидает решения')
  const bookingUrl = page.url()
  await logout(page)
  await login(page, coachEmail)
  await page.getByRole('button', { name: 'Одобрить', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Одобрить', exact: true })).toHaveCount(0)
  await logout(page)
  await login(page, clientEmail)
  await page.goto(bookingUrl)
  await expect(page.locator('.booking-state')).toContainText('Подтверждена')
  await page.getByLabel('Причина отмены', { exact: true }).fill('Изменились планы')
  await page.getByRole('button', { name: 'Отменить запись', exact: true }).click()
  await expect(page.locator('.booking-state')).toContainText('Отменена')
  await page.goto('/training')
  await expect(page.locator('.staff-table')).toContainText('Доступно')
  await logout(page)
  await login(page, 'browser-admin@example.com')
  await page.getByRole('button', { name: 'Отчёты', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Скачать PDF' })).toBeVisible()
  for (const format of ['PDF', 'DOCX', 'XLSX']) {
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Скачать ' + format }).click()
    await (await download).saveAs(testInfo.outputPath('sales.' + format.toLowerCase()))
  }
  await page.screenshot({ path: testInfo.outputPath('admin-reports-ru.png'), fullPage: true })
  await page.getByRole('button', { name: 'Обмен данными', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Экспорт тарифов' }).click()
  const filename = testInfo.outputPath('offers.json')
  await (await download).saveAs(filename)
  await page.getByLabel('Файл для импорта').setInputFiles(filename)
  await page.getByRole('button', { name: 'Проверить файл' }).click()
  await expect(page.getByRole('status')).toContainText('Файл проверен')
  await page.getByRole('button', { name: 'Применить импорт' }).click()
  await expect(page.getByRole('status')).toContainText('Импорт завершён')
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await page.setViewportSize({ width: 320, height: 850 })
  await page.getByRole('button', { name: 'Users', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('admin-en-320.png'), fullPage: true })
  expect(errors).toEqual([])
})
